def notes(text, *, detailed=False):
    lines = text.splitlines(keepends=True)
    out = []
    i = 0
    while i < len(lines):
        start = i
        while i < len(lines) and lines[i].startswith('|'):
            i += 1
        if start == i:
            out.append(lines[i])
            i += 1
            continue
        out.extend(lines[start:i])
        header = lines[start].split('|')[1].strip()
        note = (DETAIL if detailed else SUMMARY).get(header)
        line = lines[start]
        if not detailed and header == '路线':
            note = ('路线标识执行方案，本卡维度为 [M,N,K]。DT/PR 列按列头给出预测与 CA，时间均为设备微秒；DT/PR 比值大于 1 表示 PR 更快。970DT 如列出为外推。')
        if not detailed and header == '投影':
            if '模型 · 线性层' in line:
                note = '投影编号关联后续误差表，模型与层是形状来源，调度给出请求阶段和批量，本卡 [M,N,K] 是本地矩阵乘几何。'
            elif 'AIC' in line:
                note = '投影编号关联输入表。各核数按 v1.3/v1.4/CA 顺序列示；AIC 为实发 MMAD 的核，启动 AIV 包含已派发核，生产 AIV 仅计权重展开。'
            else:
                note = '投影编号关联输入表。DT、PR 时间和 DT/PR 加速比按 v1.3/v1.4/CA 顺序列出。现版误差为 v1.4 对 CA 的有符号相对误差。970DT 外推为 v1.4 预测的设备微秒。'
        if note and not ''.join(lines[i:i+3]).lstrip().startswith('**列说明**'):
            out.append('\n**列说明**　' + note + '\n')
    return ''.join(out)
